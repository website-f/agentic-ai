#!/usr/bin/env node
/**
 * Agentic Office (P105). Fauzan approved 24 database modules that are NOT on the release list (15 Nov 2026: "Let him run
 * the 24 package"; db/office-non-release.json). Two of them change tables that release modules own: business-walls-v1
 * forces row security and adds bw_wall on the tender tables (tender_opportunities), and bulk-load-ok-v1 adds
 * org_imports_ceo_read on org_imports (org_links). The release check compares those modules with their fingerprints and
 * would then call the release not ready (and prima-api would not start). This script builds a DISPOSABLE localhost
 * database, installs the base and the release modules, takes the catalogue (the same query as the fingerprints), installs
 * the 24 modules in order, and records ONLY what they add or change on release modules' catalogue entries. The release
 * check accepts exactly these values; any other change is still refused. Names and definitions only, never data.
 *   DATABASE_URL=postgres://postgres:<pw>@localhost:5432/postgres node scripts/office-module-allowances.cjs [--check]
 * Writes apps/api/src/office-module-allowances.ts; --check fails when the committed file differs.
 */
const {Client}=require('pg');const {readFileSync,writeFileSync}=require('node:fs');const {resolve}=require('node:path');
const ROOT=resolve(__dirname,'..');const base=process.env.DATABASE_URL??'postgres://postgres:localdev@localhost:5432/postgres';
if(!['localhost','127.0.0.1','::1','[::1]'].includes(new URL(base).hostname))throw Error('Disposable localhost database required');
const DB='prima_office_allowances',OWNER='prima_office_allow_owner';
const url=(role)=>{const u=new URL(base);u.pathname='/'+DB;if(role){u.username=role;u.password='local-test-only';}return u.toString();};
const manifest=JSON.parse(readFileSync(resolve(ROOT,'db/release-manifest.json'),'utf8'));
const extra=JSON.parse(readFileSync(resolve(ROOT,'db/office-non-release.json'),'utf8')).modules;
const fpSrc=readFileSync(resolve(ROOT,'apps/api/src/release-module-fingerprints.ts'),'utf8');
const Q=JSON.parse(/export const FINGERPRINT_QUERY = (".*");/.exec(fpSrc)[1]);
const FP=JSON.parse(/export const MODULE_FINGERPRINTS: Record<string, Record<string, string>> = ([\s\S]*);\s*$/.exec(fpSrc)[1]);
const OUT=resolve(ROOT,'apps/api/src/office-module-allowances.ts');
const snap=async(c)=>new Map((await c.query(Q)).rows.map(r=>[r.k,r.v]));
(async()=>{
 const admin=new Client({connectionString:base});await admin.connect();
 try{await admin.query(`DROP DATABASE IF EXISTS ${DB} WITH(FORCE)`);
  if(!(await admin.query("SELECT 1 FROM pg_roles WHERE rolname='prima_app'")).rowCount)await admin.query('CREATE ROLE prima_app NOLOGIN');
  if(!(await admin.query('SELECT 1 FROM pg_roles WHERE rolname=$1',[OWNER])).rowCount)await admin.query(`CREATE ROLE ${OWNER} LOGIN CREATEDB CREATEROLE NOSUPERUSER NOBYPASSRLS PASSWORD 'local-test-only'`);
  await admin.query(`GRANT prima_app TO ${OWNER}`);await admin.query(`CREATE DATABASE ${DB} OWNER ${OWNER}`);}finally{await admin.end();}
 const c=new Client({connectionString:url(OWNER)});await c.connect();const allow={};
 try{
  await c.query(readFileSync(resolve(ROOT,manifest.base.path),'utf8'));
  for(const m of manifest.modules)await c.query(readFileSync(resolve(ROOT,m.path),'utf8'));
  const before=await snap(c);
  for(const m of extra)await c.query(readFileSync(resolve(ROOT,'db/modules',m.file),'utf8'));
  const after=await snap(c);
  const fpKeys=new Set(Object.values(FP).flatMap(f=>Object.keys(f)));
  const fpTables=new Set([...fpKeys].filter(k=>k.startsWith('table:')).map(k=>k.slice(6)));
  for(const [k,v] of after){
   const m=/^(policy|trigger):([^.]+)\./.exec(k);
   if(fpKeys.has(k)&&before.get(k)!==v)allow[k]=v;                       // a release entry the 24 change
   else if(!before.has(k)&&m&&fpTables.has(m[2])&&!fpKeys.has(k))allow[k]=v; // a policy or trigger they add on a release table
  }
  for(const k of fpKeys)if(before.has(k)&&!after.has(k))throw Error(`the office modules remove release entry ${k}`);
 }finally{await c.end();const a=new Client({connectionString:base});await a.connect();try{await a.query(`DROP DATABASE IF EXISTS ${DB} WITH(FORCE)`);}finally{await a.end();}}
 const sorted=Object.fromEntries(Object.entries(allow).sort(([a],[b])=>a<b?-1:1));
 const text=`// GENERATED by scripts/office-module-allowances.cjs (Agentic Office, P105) on a disposable local database: what the\n// 24 approved modules off the release list (db/office-non-release.json) add or change on release modules' catalogue\n// entries. The release check accepts exactly these values. Do not edit by hand. Names and catalogue properties only.\nexport const OFFICE_MODULE_ALLOWANCES: Record<string, string> = ${JSON.stringify(sorted,null,1)};\n`;
 if(process.argv.includes('--check')){if(readFileSync(OUT,'utf8')!==text){console.error('office-module-allowances.ts is out of date: run node scripts/office-module-allowances.cjs');process.exitCode=1;}else console.log('office allowances match');}
 else{writeFileSync(OUT,text);console.log(`wrote ${Object.keys(sorted).length} allowed catalogue entries`);}
})().catch(e=>{console.error(e.message);process.exitCode=1;});
